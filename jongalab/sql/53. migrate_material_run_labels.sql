-- 2026-08-05: 재료 지속성의 **가격 채점** 라벨 (mat_run_ret_3d, mat_up_days)
--
-- [왜 새 정답지가 필요한가]
-- 지금까지 지속성 라벨의 유일한 사후 채점은 `news_followup_days`(시세보도 제외 언급 날짜 수)
-- 였다. 그런데 이 프로젝트가 쓰는 '지속성'의 뜻은 **주가를 이어서 올려주는 성질**이고, 언급이
-- 계속되는 것과는 다르다(언급 지속성은 이미 시총 프록시로 기각됐다).
-- 실측(7/29~8/3)에서도 followup_days 는 단조성이 없었다: fu=4 +0.69%p / fu=2 +0.11%p /
-- fu=1 -1.23%p / fu=0 +0.25%p. 라벨이 맞았는지 판정하는 자로 못 쓴다.
--
-- [정의 — 앵커는 익일 시가다]
--   mat_run_ret_3d : (D+3 종가 − D+1 시가) / D+1 시가 × 100
--   mat_up_days    : D+1~D+3 중 **전일 종가 대비 상승 마감**한 거래일 수 (0~3)
-- D+1 시가를 앵커로 잡는 이유: 종가베팅은 D+1 시가에 청산하므로, 그 시점 **이후**의 상승이
-- "재료가 계속 올려줬는가"의 순수한 측정이다. 리포트일 종가를 앵커로 쓰면 오버나잇 갭(이미
-- next_open_ret 이 측정하는 값)이 섞여 두 축이 구분되지 않는다.
-- D±35% 초과는 분할·데이터 아티팩트로 보고 버린다(next_* 라벨과 같은 가드).
--
-- [연구 전용 — 매매 경로 아님]
-- 이 두 컬럼은 **라벨 품질 채점용**이다. 현행 전략은 D+1 시가에 전량 청산하므로 이 구간의
-- 수익은 실현되지 않는다. '연속 재료일 때만 잔량을 더 들고 간다'는 조건부 청산 지연이 이
-- 채점으로 검증되면 그때 자금 경로(trading/)를 손대고, 그 전까지는 관측만 한다
-- (무조건 잔량 트레일링은 2026-08-03 에 65/66건 손해로 기각된 이력이 있다).
--
-- [채점 대상] news_durability IS NOT NULL 인 행만(하루 ~20종목). 라벨 없는 행에는 채점할
-- 대상이 없고, 전 유니버스로 돌리면 키움 일봉 호출이 수백 종목으로 늘어난다.

ALTER TABLE daily_stock_report
    ADD COLUMN mat_run_ret_3d DECIMAL(8,3) DEFAULT NULL
        COMMENT '재료 채점: 익일 시가 → D+3 종가 등락률(%)',
    ADD COLUMN mat_up_days TINYINT DEFAULT NULL
        COMMENT '재료 채점: D+1~D+3 중 상승 마감 일수(0~3)';
