-- 2026-08-05: 재료 신선도 축 `news_material_age_h` (선정 시점 파생, LLM 무관)
--
-- [초점] 사용자 정의: "재료의 지속성 = 오늘 재료가 **내일도 지속적으로 매수할만한가**".
-- 그 판단을 가르는 사실 중 가장 결정적인 하나가 **오늘 이미 소화됐는지**다:
--   · 14:50 에 터진 재료 → 종가까지 반영될 시간이 없다 → 내일 아침에 반응한다
--   · 08:00 에 터진 재료 → 하루 종일 반영됐다 → 내일 아침 살 사람은 이미 샀다
-- 이건 재료의 '성질'이 아니라 '시각'이라 LLM 이 필요 없다 — 결정론으로 계산한다(사실 층 유지).
--
-- [정의] closing_bet 실행 시각 − (판정 코퍼스의 **당일 최신 재료 기사** 발행시각), 시간 단위.
--   · 코퍼스는 귀속 확인(mentions_ticker) + 시세보도 제외(is_price_report) 후의 것이다 —
--     "XX 급등" 기사가 최신이라고 그걸 신선한 재료로 세면 역인과가 섞인다.
--   · 0~24 로 클램프(발행시각 미래 이상치 방어). 재료가 없으면 NULL(rule 미개입).
--   · 실행 회차마다 재계산(last-write-wins)이라 **매수 시점(마지막 회차)에 가장 가까운 값**이
--     남는다. ob_* 스냅샷과 같은 정책이고, 코퍼스 조회 실패 회차의 NULL 은 보존 대상이다.
--
-- [왜 news_pm_count 로 부족한가] 같은 축을 이미 재고 있지만 두 가지가 다르다:
--   ① `news_pm_count` 는 **카운트 게이트(telegram)** 값이라 종목 커버리지가 44% 다(네이버 94%).
--      네이버에만 뜬 14:50 재료는 pm_count=0 이라 축이 아예 안 잡힌다.
--   ② 건수라 '몇 시'를 잃는다 — 12:01 과 14:59 가 같은 1건이다. 종가베팅에서 그 둘은 다르다.
--
-- [rule 은 지금 등록하지 않는다] 축만 먼저 쌓는다. candidate 가 이미 37종이고(이 프로젝트
-- 시뮬레이션: 후보 24종이면 기대 오탐 5.2건) 이 컬럼은 오늘부터 표본이 0 이라 지금 룰을 만들면
-- 근거 없는 시험을 하나 더 늘리는 것이다. 2~3주 뒤 분포를 보고 지속성 축과 **결합**해 등록한다
-- (예: '연속 재료 & 장 마감 직전 발생' — 내일 아침 매수 논리가 가장 직접적인 조합).

ALTER TABLE daily_stock_report
    ADD COLUMN news_material_age_h DECIMAL(5,1) DEFAULT NULL
        COMMENT '재료 신선도: 당일 최신 재료 기사 경과 시간(h, 선정 시점 기준)';
