-- 2026-08-05: news_mention 에 기사 리드문 발췌(body_preview) 추가
--
-- [왜]
-- 재료 지속성 판정(core/news_material_judge)의 품질 천장이 "본문이 없다" 였다. 저장된 게
-- 헤드라인뿐이라 다음 두 축을 물을 수 없었다:
--   · 촉매가 **언제** 오는가 (milestone_horizon) — 제목에 날짜가 안 실린다
--   · 재료의 **규모** (material_size_krw) — 제목은 "대규모 수주" 로 끝난다
-- 그래서 마일스톤은 '존재 여부'만 묻고 있었고, 그 결과 `next_milestone=1` 집단에 '내일 결정'과
-- '내년 어느 날'이 같이 들어갔다. 종가베팅은 하루짜리 보유라 그 둘은 완전히 다른 재료다.
--
-- [어디서 오나]
-- 네이버 종목별 뉴스 JSON 응답에 `body`(리드문 ~135자)가 이미 오는데 파서가 버리고 있었다
-- (core/naver_news_client 주석 "body(발췌, 현재 미사용)"). 새 수집 경로·API 키·크롤링이
-- 필요 없다 — 이미 받는 응답에서 한 필드를 더 꺼내 저장하기만 한다.
-- 텔레그램 경로는 채널 메시지가 제목 한 줄이라 NULL 로 남는다(재료 판정은 두 소스를 섞어
-- 보므로, 발췌가 있는 기사만 근거가 풍부해지는 형태로 자연 축적된다).
--
-- [소급 없음] 과거 행은 NULL 이다 — 네이버 응답은 최근 40건만 주므로 되돌려 채울 수 없다.
-- 판정은 발췌 없이도 종전과 동일하게 동작한다(프롬프트가 '제목만 있으면 제목으로 판단'을
-- 명시하고, 판정 불가 축은 null 로 두게 돼 있다).

ALTER TABLE news_mention
    ADD COLUMN body_preview VARCHAR(500) DEFAULT NULL
        COMMENT '기사 리드문 발췌(네이버 종목별 경로만, 재료 판정 근거)';
