-- 2026-08-05: 재료 지속성 축 v2 — 촉매 시점·재료 규모·합성 규칙 버전
--
-- [왜 v2 인가] 2026-07-29~08-03 실측(익일 시가, 같은 날 초과수익, n=71 라벨 / 4거래일):
--   stage='마무리'        -1.66%p (t=-2.79)  ← 유일하게 유의. '소진 배제'는 실체가 있다
--   stage='진행'          -1.25%p (t=-1.76)
--   next_milestone=1      +0.70%p (t=+0.58)  ← 방향 정합
--   amount_locked 1 vs 0  -0.13 / +0.15%p    ← **무차별**
--   합성 '연속' +0.77%p / '중립' +0.85%p     ← 중립이 연속보다 높다 = 합성 규칙 역전
-- 원인: v1 합성은 `next_milestone=1 & amount_locked=0` 을 '연속'의 주 조건으로 써서, 유효한 축
-- (milestone)을 무차별 축(locked)으로 가리고 있었다. 그리고 마일스톤의 **시점**을 묻지 않아
-- '내일 결정'과 '내년 어느 날'이 같은 집단에 들어갔다 — 하루 보유 전략에서 그 둘은 다른 재료다.
--
-- [익일 장중 검정 — 이 축을 쓰는 진짜 이유]
-- "주가를 이어서 올려주는가"는 익일 **시가 이후** 구간에서 드러난다:
--   연속 n=19: 익일 장중 +2.39%(초과 +0.79%p), **양수율 84%**
--   소진 n=37: +0.80%(-0.82%p), 46%  /  중립 n=15: +0.40%(-1.27%p), 47%
-- 현행 파이프라인은 09:28 전량청산이라 이 구간을 쓰지 않는다. 청산 지연은 자금 경로이므로
-- candidate 채점을 먼저 쌓는다(무조건 잔량 트레일링은 2026-08-03 에 65/66건 손해로 기각된
-- 이력이 있다 — '연속 조건부'는 그와 다른 가설이라 별도 검증 대상이다).
--
-- [컬럼 3개]
--   news_milestone_horizon   — LLM 사실 축(1주내|1개월내|그이후|불명)
--   news_material_size_ratio — 파생: LLM 이 뽑은 재료 금액(원) ÷ market_cap(원).
--                              절대 금액을 쓰면 대형주 뉴스가 전부 '큰 재료'가 된다(언급 수
--                              라벨이 시총 프록시로 판명난 것과 같은 함정) → 비율로 저장한다.
--                              금액 원본은 저장하지 않는다 — 비율만 predicate 에 쓰이고, 원본은
--                              news_label_reason 문장에 남는다.
--   news_durability_v        — 합성 규칙 버전(현재 2). 라벨이 있을 때만 채운다.
--
-- [표본 분리] 기존 v1 라벨(7/29~8/5, 71행)은 v 가 NULL 로 남는다. 지속성 rule 2종은
-- sql/54 에서 registered_at 을 리셋해 v2 표본으로 다시 발견창을 시작한다 — v1/v2 를 섞어
-- 채점하면 정의가 다른 라벨로 게이트를 통과시키는 셈이 된다.

ALTER TABLE daily_stock_report
    ADD COLUMN news_milestone_horizon VARCHAR(10) DEFAULT NULL
        COMMENT '재료 다음 사건 시점(1주내|1개월내|그이후|불명)',
    ADD COLUMN news_material_size_ratio DECIMAL(10,4) DEFAULT NULL
        COMMENT '재료 금액 ÷ 시가총액 (LLM 추출 금액의 코드 파생)',
    ADD COLUMN news_durability_v TINYINT DEFAULT NULL
        COMMENT '지속성 합성 규칙 버전(라벨 있을 때만)';
